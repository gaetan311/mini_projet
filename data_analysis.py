from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Image, Table, TableStyle
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors

def generate_pdf_report(output_path: str, metrics: list, charts: list):
    """Génère un rapport d'analyse unifié complet et structuré graphiquement."""
    # Configuration du document avec des marges standards (2 cm)
    doc = SimpleDocTemplate(
        output_path,
        pagesize=letter,
        rightMargin=54, leftMargin=54,
        topMargin=54, bottomMargin=54
    )
    story = []

    # Configuration des styles personnalisés
    base_styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        'DocTitle',
        parent=base_styles['Title'],
        fontName='Helvetica-Bold',
        fontSize=24,
        leading=28,
        textColor=colors.HexColor("#1A365D"),  # Bleu marine corporatif
        alignment=0,  # Aligné à gauche
        spaceAfter=15
    )

    h1_style = ParagraphStyle(
        'SectionH1',
        parent=base_styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=14,
        leading=18,
        textColor=colors.HexColor("#2B6CB0"),  # Bleu secondaire
        spaceBefore=18,
        spaceAfter=10,
        keepWithNext=True
    )

    body_style = ParagraphStyle(
        'BodyTextCustom',
        parent=base_styles['BodyText'],
        fontName='Helvetica',
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#2D3748")  # Gris foncé lisible
    )

    table_header_style = ParagraphStyle(
        'TableHeader',
        parent=body_style,
        fontName='Helvetica-Bold',
        textColor=colors.white
    )

    # 1. En-tête et Titre principal
    story.append(Paragraph("Rapport d'Analyse Avancé Multimodèle", title_style))
    story.append(Paragraph("Généré automatiquement par le pipeline d'analyse modulaire.", body_style))
    story.append(Spacer(1, 15))

    # Ligne de séparation colorée
    sep_table = Table([[""]], colWidths=[504], rowHeights=[2])
    sep_table.setStyle(TableStyle([('BACKGROUND', (0,0), (-1,-1), colors.HexColor("#2B6CB0"))]))
    story.append(sep_table)
    story.append(Spacer(1, 15))

    # 2. Section Métriques d'apprentissage (Sous forme de Tableau)
    story.append(Paragraph("1. Métriques de Performance des Modèles", h1_style))
    story.append(Paragraph("Le tableau ci-dessous récapitule les scores obtenus pour chaque type d'apprentissage exécuté :", body_style))
    story.append(Spacer(1, 10))

    # Construction des lignes du tableau de bord
    table_data = [[Paragraph("Type de Modèle", table_header_style), Paragraph("Détails et Métriques Associées", table_header_style)]]
    for m in metrics:
        model_type = m.get('type', 'Inconnu')
        # Formatage propre des dictionnaires de métriques en chaînes lisibles
        details_str = ", ".join([f"<b>{k}</b>: {v}" for k, v in m.items() if k != 'type'])
        table_data.append([
            Paragraph(f"<b>{model_type}</b>", body_style),
            Paragraph(details_str, body_style)
        ])

    # Application d'un style de tableau épuré et professionnel
    metrics_table = Table(table_data, colWidths=[130, 374])
    metrics_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#1A365D")),  # En-tête bleu marine
        ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('BOTTOMPADDING', (0, 0), (-1, 0), 8),
        ('TOPPADDING', (0, 0), (-1, 0), 8),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.HexColor("#F7FAFC"), colors.white]), # Alternance gris/blanc
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),  # Bordures fines grises
        ('TOPPADDING', (0, 1), (-1, -1), 6),
        ('BOTTOMPADDING', (0, 1), (-1, -1), 6),
    ]))
    story.append(metrics_table)
    story.append(Spacer(1, 20))

    # 3. Section Visualisations graphiques (Mise en page Grid/Côte à côte)
    story.append(Paragraph("2. Visualisations Graphiques Exploratoires", h1_style))
    story.append(Spacer(1, 5))

    # Organisation des graphiques deux par deux pour maximiser l'espace
    grid_data = []
    current_row = []

    for chart in charts:
        try:
            img = Image(chart, width=240, height=170)
            current_row.append(img)
        except Exception:
            current_row.append(Paragraph(f"<i>Image manquante : {chart}</i>", body_style))

        if len(current_row) == 2:
            grid_data.append(current_row)
            current_row = []

    if current_row:
        current_row.append("")  # Cellule vide si nombre impair d'images
        grid_data.append(current_row)

    if grid_data:
        chart_table = Table(grid_data, colWidths=[252, 252])
        chart_table.setStyle(TableStyle([
            ('ALIGN', (0,0), (-1,-1), 'CENTER'),
            ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
            ('BOTTOMPADDING', (0,0), (-1,-1), 10),
        ]))
        story.append(chart_table)

    # Génération finale du livrable
    doc.build(story)
    print(f"📄 Rapport PDF professionnel généré avec succès : {output_path}")
