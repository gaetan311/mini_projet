def clean_data(df: pd.DataFrame) -> pd.DataFrame:
    """Nettoie le DataFrame de base (suppression des doublons)."""
    df_cleaned = df.drop_duplicates()
    return df_cleaned

def knn_impute_missing(df: pd.DataFrame, n_neighbors: int = 5) -> pd.DataFrame:
    """Impute les valeurs manquantes des colonnes numériques via KNNImputer."""
    df_imputed = df.copy()
    num_cols = df_imputed.select_dtypes(include=['number']).columns

    if len(num_cols) > 0 and df_imputed[num_cols].isnull().any().any():
        imputer = KNNImputer(n_neighbors=n_neighbors)
        df_imputed[num_cols] = imputer.fit_transform(df_imputed[num_cols])
        print(f"🔹 Imputation KNN complétée ({n_neighbors} voisins) sur les colonnes numériques.")
    return df_imputed

def handle_outliers(df: pd.DataFrame, columns: list) -> pd.DataFrame:
    """Cap les valeurs aberrantes via la méthode de l'écart interquartile (IQR)."""
    df_out = df.copy()
    for col in columns:
        if col in df_out.columns and pd.api.types.is_numeric_dtype(df_out[col]):
            Q1 = df_out[col].quantile(0.25)
            Q3 = df_out[col].quantile(0.75)
            IQR = Q3 - Q1
            lower_bound = Q1 - 1.5 * IQR
            upper_bound = Q3 + 1.5 * IQR
            df_out[col] = df_out[col].clip(lower=lower_bound, upper=upper_bound)
    print(f"🔹 Valeurs aberrantes traitées pour : {columns}")
    return df_out

def encode_categorical(df: pd.DataFrame, categorical_cols: list) -> pd.DataFrame:
    """Encode les variables textuelles/catégorielles en valeurs numériques (One-Hot)."""
    df_encoded = df.copy()
    valid_cols = [c for c in categorical_cols if c in df_encoded.columns]

    if valid_cols:
        encoder = OneHotEncoder(sparse_output=False, handle_unknown='ignore')
        encoded_data = encoder.fit_transform(df_encoded[valid_cols])
        encoded_cols = encoder.get_feature_names_out(valid_cols)

        df_encoded_meta = pd.DataFrame(encoded_data, columns=encoded_cols, index=df_encoded.index)
        df_encoded = pd.concat([df_encoded.drop(columns=valid_cols), df_encoded_meta], axis=1)
        print(f"🔹 Colonnes catégorielles encodées : {valid_cols}")
    return df_encoded

def feature_scaling(df: pd.DataFrame, columns: list) -> pd.DataFrame:
    """Normalise les colonnes numériques (Min-Max Scaling entre 0 et 1)."""
    df_scaled = df.copy()
    for col in columns:
        if col in df_scaled.columns:
            min_val = df_scaled[col].min()
            max_val = df_scaled[col].max()
            if max_val != min_val:
                df_scaled[col] = (df_scaled[col] - min_val) / (max_val - min_val)
    print(f"🔹 Normalisation min-max appliquée sur : {columns}")
    return df_scaled

